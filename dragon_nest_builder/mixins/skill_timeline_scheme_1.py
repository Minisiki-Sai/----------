SKILL_BURST_STOP_BOUNDARY_TAIL_SECONDS = 2.0


class SkillTimelineScheme1Mixin:
    """Independent receding-horizon policy for automatic skill timelines.

    The legacy scheduler remains the runtime/state authority.  This policy does
    not consume its one-step rank, job-specific tie breakers, or post-build
    reorder passes.  It plans from the legal actions and current runtime state,
    executes only the first action, then plans again from the resulting state.
    """

    def _skill_burst_new_scheme_1_enabled(self) -> bool:
        forced = getattr(self, "_skill_burst_force_new_scheme_1", None)
        if forced is not None:
            return bool(forced)
        if getattr(self, "_skill_burst_disable_new_scheme_1", False):
            return False
        return True

    @classmethod
    def _skill_burst_new_scheme_1_freeze(cls, value: Any) -> Any:
        if isinstance(value, dict):
            return tuple(
                sorted(
                    (norm(key), cls._skill_burst_new_scheme_1_freeze(item))
                    for key, item in value.items()
                )
            )
        if isinstance(value, (list, tuple)):
            return tuple(cls._skill_burst_new_scheme_1_freeze(item) for item in value)
        if isinstance(value, (set, frozenset)):
            return tuple(
                sorted(cls._skill_burst_new_scheme_1_freeze(item) for item in value)
            )
        if isinstance(value, float):
            return round(value, 9)
        if value is None or isinstance(value, (str, int, bool)):
            return value
        return repr(value)

