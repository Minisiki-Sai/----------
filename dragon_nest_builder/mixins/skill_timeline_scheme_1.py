    def _skill_burst_new_scheme_1_cached_result(
        self,
        cache_key: tuple[Any, ...],
    ) -> tuple[list[dict[str, Any]], float] | None:
        cache = getattr(self, "_skill_burst_new_scheme_1_result_cache", {})
        entry = cache.get(cache_key) if isinstance(cache, dict) else None
        if not isinstance(entry, dict):
            return None
        self._skill_burst_generated_effect_windows = copy.deepcopy(
            entry.get("effect_windows", [])
        )
        self._skill_burst_periodic_buffs = copy.deepcopy(entry.get("periodic_buffs", []))
        self._skill_burst_new_scheme_1_last_quality = copy.deepcopy(
            entry.get("quality", {})
        )
        self._skill_burst_new_scheme_1_last_quality["cached"] = True
        return copy.deepcopy(entry.get("segments", [])), as_number(entry.get("window"))

    def _skill_burst_new_scheme_1_store_result(
        self,
        cache_key: tuple[Any, ...],
        segments: list[dict[str, Any]],
        window: float,
    ) -> None:
        cache = getattr(self, "_skill_burst_new_scheme_1_result_cache", None)
        if not isinstance(cache, dict):
            cache = {}
            self._skill_burst_new_scheme_1_result_cache = cache
        cache[cache_key] = {
            "segments": copy.deepcopy(segments),
            "window": max(0.0, as_number(window)),
            "effect_windows": copy.deepcopy(
                getattr(self, "_skill_burst_generated_effect_windows", [])
            ),
            "periodic_buffs": copy.deepcopy(
                getattr(self, "_skill_burst_periodic_buffs", [])
            ),
            "quality": copy.deepcopy(
                getattr(self, "_skill_burst_new_scheme_1_last_quality", {})
            ),
        }
        while len(cache) > 32:
            cache.pop(next(iter(cache)))

    def _skill_burst_new_scheme_1_profile(
        self,
        window: float,
    ) -> tuple[float, int, int, int, int]:
        """Return horizon, depth, beam width, branch width and root width."""
        if getattr(self, "_skill_burst_fast_mechanism_policy", False):
            profile = tuple(
                getattr(self, "_skill_burst_fast_mechanism_profile", ())
            )
            if len(profile) == 5:
                return (
                    max(1.0, as_number(profile[0], 4.0)),
                    max(1, int(as_number(profile[1], 2))),
                    max(1, int(as_number(profile[2], 1))),
                    max(1, int(as_number(profile[3], 2))),
                    max(1, int(as_number(profile[4], 1))),
                )
            return 4.0, 2, 1, 2, 1
        if getattr(self, "_skill_burst_complete_default_rotation", False):
            return 4.0, 2, 2, 3, 2
        if window >= 120:
            return 6.0, 2, 2, 3, 2
        return 5.0, 3, 2, 3, 2

    def _skill_burst_new_scheme_1_cooldown_links(self, skill: str) -> set[str]:
        skill_key = self._skill_burst_skill_key(skill)
        links = {
            target_skill
            for target_skill, _source in self._skill_burst_cooldown_rule_sources_for(
                skill_key
            )
        }
        rules = (
            self.store.skill_cooldown_rules()
            .get("jobs", {})
            .get(norm(self.second_job.currentText()), {})
        )
        if isinstance(rules, dict):
            target_rule = rules.get(skill_key, {})
            if isinstance(target_rule, dict):
                links.update(
                    self._skill_burst_skill_key(source.get("skill"))
                    for source in target_rule.get("sources", [])
                    if isinstance(source, dict)
                    and self._skill_burst_skill_key(source.get("skill"))
                )
        links.discard(skill_key)
        return links

    @staticmethod
    def _skill_burst_new_scheme_1_merge_attrs(
        base: dict[str, Any],
        extra: dict[str, Any],
    ) -> dict[str, Any]:
        merged = copy.deepcopy(base)
        for key, value in extra.items():
            if norm(key).startswith("__"):
                merged[key] = copy.deepcopy(value)
            else:
                merged[key] = as_number(merged.get(key)) + as_number(value)
        return merged

    def _skill_burst_new_scheme_1_metric_value(
        self,
        metric: dict[str, Any],
        attrs: dict[str, Any],
        start: float,
        window: float,
        previous_skill: str,
        support_actions: list[dict[str, Any]] | None = None,
    ) -> tuple[float, float]:
        cache = getattr(self, "_skill_burst_new_scheme_1_metric_value_cache", None)
        if not isinstance(cache, dict):
            cache = {}
            self._skill_burst_new_scheme_1_metric_value_cache = cache
        # State helpers return defensive copies. Equal attribute values are
        # the same scoring input even when their dict identities differ.
        # Keep all values exact (no extra rounding) and remain axis-local.
        try:
            attrs_signature = tuple(sorted(attrs.items()))
            hash(attrs_signature)
        except (TypeError, ValueError):
            attrs_signature = None
        cache_key = (
            id(metric),
            ('values', attrs_signature) if attrs_signature is not None else ('identity', id(attrs)),
            round(max(0.0, as_number(start)), 6),
            round(max(0.0, as_number(window)), 6),
            self._skill_burst_skill_key(previous_skill),
            id(support_actions),
        )
        cached = cache.get(cache_key)
        anchor = metric if attrs_signature is not None else attrs
        if isinstance(cached, tuple) and len(cached) == 3 and cached[0] is anchor:
            return cached[1], cached[2]
        skill = self._skill_burst_skill_key(metric.get("skill"))
        cast_time = self._skill_burst_scheduled_cast_time(
            skill,
            start,
            previous_skill,
            attrs,
        )
        if cast_time <= 0 or start >= window - 1e-6:
            cache[cache_key] = (anchor, 0.0, 0.0)
            return 0.0, 0.0
        cast_attrs = self._skill_burst_attrs_for_cast(attrs, skill)
        for action in support_actions or []:
            if self._skill_burst_skill_key(action.get("skill")) != skill:
                continue
            if self._skill_burst_action_starts_on_cast(action):
                cast_attrs = self._skill_burst_attrs_during_action(
                    cast_attrs,
                    action,
                )
            break
        score = self._skill_burst_window_metric_score(
            metric,
            cast_attrs,
            start,
            window,
            cast_time,
        )
        result = (max(0.0, score), cast_time)
        cache[cache_key] = (anchor, *result)
        while len(cache) > 65536:
            cache.pop(next(iter(cache)))
        return result

    def _skill_burst_new_scheme_1_candidate_baseline(
        self,
        candidates: list[dict[str, Any]],
        base_cooldowns: dict[str, float],
    ) -> tuple[dict[str, dict[str, Any]], float, float]:
        """Cache candidate invariants reused by every decision in one rotation."""
        cached = getattr(self, "_skill_burst_new_scheme_1_candidate_cache", None)
        if (
            isinstance(cached, dict)
            and cached.get("candidates") is candidates
            and cached.get("base_cooldowns") is base_cooldowns
        ):
            return (
                cached["by_skill"],
                cached["best_dpa"],
                cached["best_cycle_dps"],
            )

        by_skill = {
            self._skill_burst_skill_key(candidate.get("skill")): candidate
            for candidate in candidates
            if self._skill_burst_skill_key(candidate.get("skill"))
        }
        best_dpa = max(
            (
                self._skill_burst_candidate_metric_dpa(candidate)
                for candidate in candidates
            ),
            default=0.0,
        )
        best_cycle_dps = max(
            (
                self._skill_burst_candidate_metric_score(candidate)
                / max(
                    0.01,
                    as_number(candidate.get("cast_time")),
                    as_number(
                        base_cooldowns.get(
                            self._skill_burst_skill_key(candidate.get("skill"))
                        )
                    ),
                )
                for candidate in candidates
            ),
            default=0.0,
        )
        self._skill_burst_new_scheme_1_candidate_cache = {
            "candidates": candidates,
            "base_cooldowns": base_cooldowns,
            "by_skill": by_skill,
            "best_dpa": best_dpa,
            "best_cycle_dps": best_cycle_dps,
        }
        return by_skill, best_dpa, best_cycle_dps

    def _skill_burst_new_scheme_1_planning_boundary(
        self,
        current: float,
        window: float,
    ) -> float:
        """Return the next point after which current damage cannot settle.

        A cast may legally cross an output-stop boundary, but candidate
        selection immediately before that boundary must compare only damage
        that can settle before the stop. Treat the next stop as a local tail
        instead of letting the rollout look through it into a later phase.
        """
        current = max(0.0, as_number(current))
        window = max(current, as_number(window))
        next_block = self._skill_burst_next_block_start(current, window)
        if current + 1e-6 < next_block < window - 1e-6:
            return next_block
        return window

    def _skill_burst_new_scheme_1_opportunity_score(
        self,
        metric: dict[str, Any],
        candidates: list[dict[str, Any]],
        damage_available_at: dict[str, float],
        base_cooldowns: dict[str, float],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        active_attrs: dict[str, Any],
        current: float,
        window: float,
        cast_time: float,
        raw_dpa: float,
        raw_score: float,
        charged_counts: dict[str, int] | None = None,
        charged_maxes: dict[str, int] | None = None,
    ) -> tuple[float, float]:
        """Score one action from the current state without legacy rankings."""
        if cast_time <= 0:
            return max(0.0, raw_dpa), 0.0
        skill = self._skill_burst_skill_key(metric.get("skill"))
        next_planning_boundary = self._skill_burst_new_scheme_1_planning_boundary(
            current,
            window,
        )
        planning_boundary = (
            next_planning_boundary
            if (
                next_planning_boundary - current
                <= SKILL_BURST_STOP_BOUNDARY_TAIL_SECONDS + 1e-6
            )
            else window
        )
        end = min(planning_boundary, current + cast_time)
        followups = (
            self._skill_burst_required_followups(skill)
            | self._skill_burst_forced_combo_followups(skill)
            | self._skill_burst_optional_combo_followups(skill)
        )
        displaced_value = 0.0
        tail_combo_replacement = 0.0
        earliest_better_ready = 0.0
        for other in candidates:
            other_skill = self._skill_burst_skill_key(other.get("skill"))
            if not other_skill or other_skill == skill or other_skill in followups:
                continue
            if not self._skill_burst_predecessor_satisfied(skill, other_skill):
                continue
            ready_at = as_number(damage_available_at.get(other_skill))
            if ready_at <= current + 1e-6 or ready_at >= end - 1e-6:
                continue
            other_score, other_cast = self._skill_burst_new_scheme_1_metric_value(
                other,
                active_attrs,
                ready_at,
                window,
                skill,
                support_actions,
            )
            other_score = max(
                other_score,
                self._skill_burst_candidate_metric_score(other),
            )
            if other_cast <= 0:
                other_cast = max(0.0, as_number(other.get("cast_time")))
            if other_cast <= 0:
                continue
            other_dpa = other_score / other_cast
            other_replacement_score = other_score
            if planning_boundary - current <= 6.0 + 1e-6:
                other_followups = (
                    self._skill_burst_required_followups(other_skill)
                    | self._skill_burst_forced_combo_followups(other_skill)
                )
                if other_followups:
                    linked_score = max(
                        (
                            self._skill_burst_candidate_metric_score(candidate)
                            for candidate in candidates
                            if self._skill_burst_skill_key(candidate.get("skill"))
                            in other_followups
                        ),
                        default=0.0,
                    )
                    other_replacement_score += linked_score
                    tail_combo_replacement = max(
                        tail_combo_replacement,
                        other_replacement_score,
                    )
                    other_dpa = max(
                        other_dpa,
                        max(
                            (
                                self._skill_burst_candidate_metric_dpa(candidate)
                                for candidate in candidates
                                if self._skill_burst_skill_key(candidate.get("skill"))
                                in other_followups
                            ),
                            default=0.0,
                        ),
                    )
                    trace = getattr(self, "_skill_burst_new_scheme_1_trace", None)
                    if isinstance(trace, list):
                        trace.append({
                            "type": "tail_combo_package",
                            "time": round(current, 5),
                            "blocked_by": skill,
                            "opener": other_skill,
                            "followups": sorted(other_followups),
                            "opener_score": other_score,
                            "linked_score": linked_score,
                            "replacement_score": other_replacement_score,
                        })
            if end >= planning_boundary - 1e-6:
                displaced_value += other_replacement_score
                earliest_better_ready = (
                    ready_at
                    if earliest_better_ready <= 0
                    else min(earliest_better_ready, ready_at)
                )
                continue
            if other_dpa <= raw_dpa + 1e-9:
                continue
            displaced_value += (other_dpa - raw_dpa) * (end - ready_at)
            earliest_better_ready = (
                ready_at
                if earliest_better_ready <= 0
                else min(earliest_better_ready, ready_at)
            )

        cooldown_value = 0.0
        wasted_cooldown_value = 0.0
        candidate_by_skill, best_candidate_dpa, best_candidate_cycle_dps = (
            self._skill_burst_new_scheme_1_candidate_baseline(
                candidates,
                base_cooldowns,
            )
        )
        external_factor = max(
            0.0,
            1.0 - self._skill_burst_sim_cdr_percent_at(current, active_attrs) / 100,
        )
        for target_skill, source in self._skill_burst_cooldown_rule_sources_for(skill):
            target = candidate_by_skill.get(target_skill)
            remaining = max(
                0.0,
                as_number(damage_available_at.get(target_skill)) - current,
            )
            if target is None:
                continue
            source_type = norm(source.get("type"))
            target_base = max(0.0, as_number(base_cooldowns.get(target_skill)))
            target_score, target_cast = self._skill_burst_new_scheme_1_metric_value(
                target,
                active_attrs,
                current,
                window,
                skill,
                support_actions,
            )
            if source_type == "grant_charge":
                # A skill can be ready while its stored stock is only 1/3 or
                # 2/3. Availability alone cannot tell whether this is wasted.
                if charged_counts is not None and target_skill in charged_counts:
                    stock = charged_counts[target_skill]
                    cap = (charged_maxes or {}).get(target_skill, stock)
                    if stock < cap and end + target_cast <= planning_boundary + 1e-6:
                        cooldown_value += max(0.0, target_score) * 0.75
                    elif stock >= cap:
                        wasted_cooldown_value += max(0.0, target_score) * 0.90
                elif remaining > 1e-6:
                    cooldown_value += max(0.0, target_score) * 0.75
                continue
            if remaining <= 1e-6:
                if target_score <= 0 or target_cast <= 0:
                    continue
                if source_type == "reset":
                    wasted_cooldown_value += target_score * 0.90
                elif source_type == "target_percent" and target_base > 0:
                    reduction = (
                        target_base
                        * max(0.0, as_number(source.get("value")))
                        * external_factor
                    )
                    wasted_cooldown_value += min(
                        target_score,
                        target_score / target_cast * reduction,
                    ) * 0.65
                continue
            if source_type in {"reset", "grant_charge"}:
                reduction = remaining
                realization = 0.75
            elif source_type == "fixed_seconds":
                reduction = max(0.0, as_number(source.get("value"))) * external_factor
                realization = 0.25
            elif source_type == "target_percent" and target_base > 0:
                reduction = target_base * max(0.0, as_number(source.get("value"))) * external_factor
                realization = 0.35
            else:
                continue
            actual_reduction = min(remaining, reduction)
            if actual_reduction <= 1e-6 or target_cast <= 0:
                continue
            recovered = target_score / target_cast * actual_reduction
            cooldown_value += min(
                recovered * realization,
                target_score * realization,
            )

        shared_ultimate_loss = 0.0
        if self._skill_burst_is_ultimate_name(skill):
            lock_cooldown = self._skill_burst_effective_cooldown(
                skill,
                max(0.0, as_number(base_cooldowns.get(skill))),
                current,
                active_attrs,
            )
            lock_until = current + max(0.0, lock_cooldown)
            reference_dpa = max(
                raw_dpa,
                max(
                    (
                        self._skill_burst_candidate_metric_dpa(candidate)
                        for candidate in candidates
                    ),
                    default=0.0,
                ),
            )
            for support_index, action in enumerate(support_actions):
                support_skill = self._skill_burst_skill_key(action.get("skill"))
                if (
                    not support_skill
                    or support_skill == skill
                    or not self._skill_burst_is_ultimate_name(support_skill)
                ):
                    continue
                ready_at = max(
                    current,
                    as_number(support_available_at.get(support_index)),
                )
                if ready_at >= min(window, lock_until) - 1e-6:
                    continue
                if as_number(support_expires_at.get(support_index)) > ready_at + 1e-6:
                    continue
                support_cast = self._skill_burst_support_cast_time(
                    action,
                    ready_at,
                    active_attrs,
                )
                duration = max(0.0, as_number(action.get("duration")))
                gain_ratio = self._skill_burst_support_gain_ratio(
                    action,
                    active_attrs,
                    ready_at,
                )
                attrs = action.get("attrs", {})
                gain_ratio += min(
                    0.70,
                    max(0.0, as_number(attrs.get("冷却缩减%"))) / 100,
                ) * 0.55
                gain_ratio += min(
                    1.00,
                    max(0.0, as_number(attrs.get("动作速度%"))) / 100,
                ) * 0.90
                if duration <= 0 or gain_ratio <= 0 or reference_dpa <= 0:
                    continue
                natural_apply = ready_at + max(0.0, support_cast)
                delayed_apply = min(
                    window,
                    lock_until + max(0.0, support_cast),
                )
                lost_uptime = min(
                    duration,
                    max(0.0, window - natural_apply),
                    max(0.0, delayed_apply - natural_apply),
                )
                shared_ultimate_loss = max(
                    shared_ultimate_loss,
                    reference_dpa * lost_uptime * gain_ratio,
                )
                if lost_uptime > 1e-6:
                    earliest_better_ready = (
                        ready_at
                        if earliest_better_ready <= 0
                        else min(earliest_better_ready, ready_at)
                    )

        urgency_value = 0.0
        base_cooldown = max(0.0, as_number(base_cooldowns.get(skill)))
        effective_cooldown = max(
            cast_time,
            self._skill_burst_effective_cooldown(
                skill,
                base_cooldown,
                current,
                active_attrs,
            ),
        )
        if base_cooldown > 1e-6 and planning_boundary > current + cast_time:
            future_uses = max(
                0,
                int((planning_boundary - current - cast_time) // base_cooldown),
            )
            latest_start = planning_boundary - cast_time - future_uses * base_cooldown
            slack = max(0.0, latest_start - current)
            urgency_span = max(0.25, min(cast_time, 2.0))
            if slack < urgency_span:
                urgency_value = raw_score * 0.15 * (1.0 - slack / urgency_span)

        # A pure DPA comparison can postpone a long animation indefinitely:
        # every short filler looks better now, while the postponed skill loses
        # an entire cooldown cycle later in the window.  Age a ready skill by
        # its own cycle throughput.  This is deliberately gradual (and capped
        # at one cooldown) so it preserves rotations without a hard deadline
        # that would force weak skills at arbitrary times.
        ready_debt_value = 0.0
        ready_since = max(0.0, as_number(damage_available_at.get(skill)))
        ready_delay = max(0.0, current - ready_since)
        own_cycle_dps = raw_score / max(
            cast_time,
            base_cooldown,
            0.01,
        )
        cycle_deadline_value = 0.0
        cycle_deadline_weight = max(
            0.0,
            as_number(
                getattr(
                    self,
                    "_skill_burst_fast_mechanism_cycle_deadline_weight",
                    0.0,
                )
            ),
        )
        if (
            getattr(self, "_skill_burst_fast_mechanism_policy", False)
            and cycle_deadline_weight > 0
            and base_cooldown > cast_time * 1.05 + 1e-9
            and not self._skill_burst_is_ultimate_name(skill)
        ):
            decision_delay = max(
                0.25,
                as_number(
                    getattr(
                        self,
                        "_skill_burst_fast_mechanism_cycle_deadline_delay",
                        2.0,
                    ),
                    2.0,
                ),
            )
            current_uses = self._skill_burst_new_scheme_1_remaining_cycle_uses(
                current,
                cast_time,
                effective_cooldown,
                window,
            )
            delayed_uses = self._skill_burst_new_scheme_1_remaining_cycle_uses(
                current + decision_delay,
                cast_time,
                effective_cooldown,
                window,
            )
            lost_uses = max(0, current_uses - delayed_uses)
            if lost_uses:
                dpa_quality = (
                    raw_dpa / best_candidate_dpa
                    if best_candidate_dpa > 1e-9
                    else 1.0
                )
                cycle_quality = (
                    own_cycle_dps / best_candidate_cycle_dps
                    if best_candidate_cycle_dps > 1e-9
                    else 1.0
                )
                quality = min(1.0, max(dpa_quality, cycle_quality))
                if quality >= 0.25:
                    cycle_deadline_value = (
                        raw_score
                        * lost_uses
                        * quality
                        * cycle_deadline_weight
                    )
        boundary_urgency_value = 0.0
        if getattr(self, "_skill_burst_fast_mechanism_policy", False):
            next_block = self._skill_burst_next_block_start(current, window)
            time_to_block = max(0.0, next_block - current)
            if (
                next_block < window - 1e-6
                and effective_cooldown > 1e-6
                and time_to_block < effective_cooldown + cast_time - 1e-6
            ):
                boundary_span = max(
                    0.5,
                    min(
                        max(
                            0.5,
                            as_number(
                                getattr(
                                    self,
                                    "_skill_burst_fast_mechanism_boundary_urgency_span",
                                    3.0,
                                ),
                                3.0,
                            ),
                        ),
                        effective_cooldown,
                    ),
                )
                boundary_slack = max(0.0, time_to_block - cast_time)
                boundary_pressure = max(
                    0.0,
                    1.0 - boundary_slack / boundary_span,
                )
                dpa_quality = (
                    raw_dpa / best_candidate_dpa
                    if best_candidate_dpa > 1e-9
                    else 1.0
                )
                cycle_quality = (
                    own_cycle_dps / best_candidate_cycle_dps
                    if best_candidate_cycle_dps > 1e-9
                    else 1.0
                )
                quality = min(1.0, max(dpa_quality, cycle_quality))
                if quality >= 0.35:
                    boundary_urgency_value = (
                        raw_score
                        * quality
                        * boundary_pressure
                        * max(
                            0.0,
                            as_number(
                                getattr(
                                    self,
                                    "_skill_burst_fast_mechanism_boundary_urgency_weight",
                                    0.35,
                                ),
                                0.35,
                            ),
                        )
                    )
        debt_dpa_floor = max(
            0.0,
            as_number(
                getattr(
                    self,
                    "_skill_burst_new_scheme_1_ready_debt_dpa_floor",
                    0.20,
                ),
                0.20,
            ),
        )
        debt_cycle_floor = max(
            0.0,
            as_number(
                getattr(
                    self,
                    "_skill_burst_new_scheme_1_ready_debt_cycle_floor",
                    0.50,
                ),
                0.50,
            ),
        )
        if (
            base_cooldown > 1e-6
            and ready_delay > 1e-6
            and planning_boundary - current > effective_cooldown + 1e-6
            and not self._skill_burst_is_ultimate_name(skill)
            and not (
                base_cooldown <= cast_time * 1.05 + 1e-9
                and not self._skill_burst_required_predecessors(skill)
            )
            and (
                best_candidate_dpa <= 1e-9
                or raw_dpa >= best_candidate_dpa * debt_dpa_floor - 1e-9
                or best_candidate_cycle_dps <= 1e-9
                or own_cycle_dps >= best_candidate_cycle_dps * debt_cycle_floor - 1e-9
            )
        ):
            debt_weight = max(
                0.0,
                as_number(
                    getattr(
                        self,
                        "_skill_burst_new_scheme_1_ready_debt_weight",
                        0.60,
                    ),
                    0.60,
                ),
            )
            ready_debt_value = (
                raw_score
                / effective_cooldown
                * min(ready_delay, effective_cooldown)
                * debt_weight
            )

        displacement_weight = max(
            0.0,
            as_number(
                getattr(
                    self,
                    "_skill_burst_new_scheme_1_displacement_weight",
                    1.0,
                ),
                1.0,
            ),
        )
        if (
            cast_time <= 0.75 + 1e-9
            and max(0.0, as_number(base_cooldowns.get(skill)))
            <= cast_time * 1.05 + 1e-9
            and not self._skill_burst_required_predecessors(skill)
        ):
            displacement_weight = min(
                displacement_weight,
                max(
                    0.0,
                    as_number(
                        getattr(
                            self,
                            "_skill_burst_new_scheme_1_short_cast_displacement_weight",
                            1.0,
                        ),
                        1.0,
                    ),
                ),
            )
        adjusted_score = (
            raw_score
            + cooldown_value
            + urgency_value
            + boundary_urgency_value
            + cycle_deadline_value
            + ready_debt_value
            - displaced_value * displacement_weight
            - wasted_cooldown_value
            - shared_ultimate_loss
        )
        if tail_combo_replacement > adjusted_score + 1e-6:
            return 0.0, earliest_better_ready
        return max(0.0, adjusted_score / cast_time), earliest_better_ready

    def _skill_burst_new_scheme_1_remaining_cycle_uses(
        self,
        start: float,
        cast_time: float,
        cooldown: float,
        window: float,
    ) -> int:
        """Count starts outside stop windows while allowing casts to cross a boundary."""
        current = max(0.0, as_number(start))
        cast = max(0.01, as_number(cast_time))
        cycle = max(cast, as_number(cooldown))
        limit = max(current, as_number(window))
        count = 0
        guard = 0
        while current + cast <= limit + 1e-6 and guard < 1024:
            guard += 1
            blocked = self._skill_burst_blocked_range_at(current)
            if blocked is not None:
                current = blocked[1]
                continue
            count += 1
            current += cycle
        return count

    def _skill_burst_new_scheme_1_apply_damage(
        self,
        metric: dict[str, Any],
        start: float,
        cast_time: float,
        attrs: dict[str, Any],
        available_at: dict[str, float],
        base_cooldowns: dict[str, float],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        charged_counts: dict[str, int],
        charged_maxes: dict[str, int],
        charged_recharge_at: dict[str, float | None],
        ammo: int,
        fury: int,
        guardian_phantoms: int,
    ) -> dict[str, Any]:
        skill = self._skill_burst_skill_key(metric.get("skill"))
        next_available = dict(available_at)
        next_support_available = dict(support_available_at)
        next_support_expires = dict(support_expires_at)
        next_counts = dict(charged_counts)
        next_recharges = dict(charged_recharge_at)
        self._skill_burst_advance_stored_charges(
            start, next_available, base_cooldowns, next_counts,
            charged_maxes, next_recharges, attrs,
        )
        next_ammo = max(0, ammo - self._skill_burst_ammo_cost(skill))
        next_fury, _boosted = self._skill_burst_apply_fury_use(fury, skill)
        next_guardian, _used = self._skill_burst_apply_guardian_phantom_use(
            guardian_phantoms,
            skill,
        )
        base_cooldown = as_number(base_cooldowns.get(skill), metric.get("base_cooldown"))
        cooldown = self._skill_burst_effective_cooldown(
            skill,
            base_cooldown,
            start,
            attrs,
        )
        if skill in next_counts:
            next_counts[skill] = max(0, next_counts.get(skill, 0) - 1)
            if next_recharges.get(skill) is None and cooldown > 0:
                next_recharges[skill] = start + cooldown
            next_available[skill] = (
                start
                if next_counts.get(skill, 0) > 0
                else as_number(next_recharges.get(skill), start + cooldown)
            )
        else:
            next_available[skill] = start + max(0.0, cooldown)
        damage_rows = {key: key for key in next_available}
        self._skill_burst_apply_shared_skill_use(
            skill,
            start,
            base_cooldown,
            support_actions,
            next_support_available,
            next_support_expires,
            next_available,
            damage_rows,
            base_cooldowns,
            attrs,
            cast_end=start + cast_time,
            charged_counts=next_counts,
            charged_maxes=charged_maxes,
            charged_recharge_at=next_recharges,
        )
        self._skill_burst_advance_stored_charges(
            start + cast_time, next_available, base_cooldowns, next_counts,
            charged_maxes, next_recharges, attrs,
        )
        return {
            "available": next_available,
            "support_available": next_support_available,
            "support_expires": next_support_expires,
            "charged_counts": next_counts,
            "charged_maxes": dict(charged_maxes),
            "charged_recharge_at": next_recharges,
            "ammo": next_ammo,
            "fury": next_fury,
            "guardian": next_guardian,
        }

    def _skill_burst_new_scheme_1_state_attrs(
        self,
        state: dict[str, Any],
        support_actions: list[dict[str, Any]],
        seconds: float,
    ) -> dict[str, Any]:
        support_expires = state["support_expires"]
        cache = getattr(
            self,
            "_skill_burst_new_scheme_1_state_attrs_cache",
            None,
        )
        if not isinstance(cache, dict):
            cache = {}
            self._skill_burst_new_scheme_1_state_attrs_cache = cache
        cache_key = (
            id(support_actions),
            id(support_expires),
            round(as_number(seconds), 6),
            int(state.get("fury", 0)),
            int(state.get("guardian", 0)),
        )
        cached = cache.get(cache_key)
        if (
            isinstance(cached, tuple)
            and len(cached) == 3
            and cached[0] is support_actions
            and cached[1] is support_expires
        ):
            return cached[2]
        attrs = self._skill_burst_active_attrs(
            support_actions,
            support_expires,
            seconds,
        )
        if self._skill_burst_uses_fury():
            attrs[SKILL_BURST_FURY_MARKER] = float(state.get("fury", 0))
        if self._skill_burst_uses_guardian_phantoms():
            attrs[SKILL_BURST_GUARDIAN_PHANTOM_MARKER] = float(
                state.get("guardian", 0)
            )
        cache[cache_key] = (support_actions, support_expires, attrs)
        while len(cache) > 16384:
            cache.pop(next(iter(cache)))
        return attrs

    def _skill_burst_new_scheme_1_terminal_value(
        self,
        state: dict[str, Any],
        candidates: list[dict[str, Any]],
        support_actions: list[dict[str, Any]],
        horizon_end: float,
        window: float,
    ) -> float:
        cache_key = (float(horizon_end), float(window))
        cached = state.get("__new_scheme_1_terminal_value")
        if (
            isinstance(cached, tuple)
            and len(cached) == 2
            and cached[0] == cache_key
        ):
            return cached[1]
        state_time = as_number(state.get("time"))
        if state.get("exact_tail"):
            value = max(0.0, as_number(state.get("score")))
            state["__new_scheme_1_terminal_value"] = (cache_key, value)
            return value
        remaining = max(0.0, horizon_end - state_time)
        if remaining <= 1e-6:
            value = max(0.0, as_number(state.get("score")))
            state["__new_scheme_1_terminal_value"] = (cache_key, value)
            return value
        attrs = self._skill_burst_new_scheme_1_state_attrs(
            state,
            support_actions,
            state_time,
        )
        required = self._skill_burst_required_followups(state.get("previous", ""))
        best_projection = 0.0
        for metric in candidates:
            skill = self._skill_burst_skill_key(metric.get("skill"))
            if required and skill not in required:
                continue
            if self._skill_burst_ammo_cost(skill) > int(state.get("ammo", 0)):
                continue
            ready_at = max(state_time, as_number(state["available"].get(skill)))
            if skill in state["charged_counts"] and state["charged_counts"].get(skill, 0) > 0:
                ready_at = state_time
            if ready_at >= horizon_end - 1e-6:
                continue
            cast_previous = self._skill_burst_immediate_predecessor(
                state.get("previous", ""),
                state_time,
                ready_at,
            )
            if not self._skill_burst_predecessor_satisfied(
                cast_previous,
                skill,
            ):
                continue
            if not self._skill_burst_state_requirement_satisfied(skill, attrs):
                continue
            score, cast_time = self._skill_burst_new_scheme_1_metric_value(
                metric,
                attrs,
                ready_at,
                window,
                cast_previous,
                support_actions,
            )
            if cast_time > 0:
                usable_time = max(0.0, horizon_end - ready_at)
                best_projection = max(
                    best_projection,
                    score / cast_time * usable_time,
                )
        value = max(0.0, as_number(state.get("score"))) + best_projection
        state["__new_scheme_1_terminal_value"] = (cache_key, value)
        return value

    def _skill_burst_new_scheme_1_rollout(
        self,
        root: tuple[float, float, float, float, dict[str, Any]],
        candidates: list[dict[str, Any]],
        damage_available_at: dict[str, float],
        base_cooldowns: dict[str, float],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        active_attrs: dict[str, Any],
        current: float,
        window: float,
        previous_skill: str,
        charged_counts: dict[str, int],
        charged_maxes: dict[str, int],
        charged_recharge_at: dict[str, float | None],
        ammo: int,
        fury: int,
        guardian_phantoms: int,
        force_exact_tail: bool = False,
    ) -> tuple[float, tuple[str, ...]]:
        horizon, max_depth, beam_width, branch_width, _root_width = (
            self._skill_burst_new_scheme_1_profile(window)
        )
        planning_boundary = self._skill_burst_new_scheme_1_planning_boundary(
            current,
            window,
        )
        exact_tail = bool(force_exact_tail) or (
            planning_boundary - current
            <= SKILL_BURST_STOP_BOUNDARY_TAIL_SECONDS + 1e-6
        )
        root_cooldown_links = self._skill_burst_new_scheme_1_cooldown_links(
            root[4].get("skill")
        )
        if exact_tail:
            max_depth = max(max_depth, 4)
            beam_width = max(beam_width, 3)
            branch_width = max(branch_width, 4)
        elif root_cooldown_links:
            max_depth = max(max_depth, 4)
        horizon_end = min(planning_boundary, current + horizon)
        root_metric = root[4]
        root_skill = self._skill_burst_skill_key(root_metric.get("skill"))
        root_score, root_cast = self._skill_burst_new_scheme_1_metric_value(
            root_metric,
            active_attrs,
            current,
            planning_boundary,
            previous_skill,
            support_actions,
        )
        if root_cast <= 0:
            return 0.0, (root_skill,)
        transition = self._skill_burst_new_scheme_1_apply_damage(
            root_metric,
            current,
            root_cast,
            active_attrs,
            damage_available_at,
            base_cooldowns,
            support_actions,
            support_available_at,
            support_expires_at,
            charged_counts,
            charged_maxes,
            charged_recharge_at,
            ammo,
            fury,
            guardian_phantoms,
        )
        states = [{
            **transition,
            "time": current + root_cast,
            "score": root_score,
            "previous": root_skill,
            "sequence": (root_skill,),
            "exact_tail": exact_tail,
        }]
        best = states[0]
        for _depth in range(1, max_depth):
            expanded: list[dict[str, Any]] = []
            for state in states:
                state_time = as_number(state.get("time"))
                if state_time >= horizon_end - 1e-6:
                    expanded.append(state)
                    continue
                attrs = self._skill_burst_new_scheme_1_state_attrs(
                    state,
                    support_actions,
                    state_time,
                )
                required = self._skill_burst_required_followups(state.get("previous", ""))
                options: list[tuple[float, float, float, dict[str, Any]]] = []
                for metric in candidates:
                    skill = self._skill_burst_skill_key(metric.get("skill"))
                    if not skill or (required and skill not in required):
                        continue
                    if self._skill_burst_ammo_cost(skill) > int(state.get("ammo", 0)):
                        continue
                    ready_at = max(state_time, as_number(state["available"].get(skill)))
                    if skill in state["charged_counts"] and state["charged_counts"].get(skill, 0) > 0:
                        ready_at = state_time
                    if ready_at >= horizon_end - 1e-6:
                        continue
                    cast_previous = self._skill_burst_immediate_predecessor(
                        state.get("previous", ""),
                        state_time,
                        ready_at,
                    )
                    if not self._skill_burst_predecessor_satisfied(
                        cast_previous,
                        skill,
                    ):
                        continue
                    future_attrs = self._skill_burst_new_scheme_1_state_attrs(
                        state,
                        support_actions,
                        ready_at,
                    )
                    if not self._skill_burst_state_requirement_satisfied(skill, future_attrs):
                        continue
                    score, cast_time = self._skill_burst_new_scheme_1_metric_value(
                        metric,
                        future_attrs,
                        ready_at,
                        planning_boundary,
                        cast_previous,
                        support_actions,
                    )
                    if cast_time <= 0:
                        continue
                    adjusted_dpa, _wait_until = (
                        self._skill_burst_new_scheme_1_opportunity_score(
                            metric,
                            candidates,
                            state["available"],
                            base_cooldowns,
                            support_actions,
                            state["support_available"],
                            state["support_expires"],
                            future_attrs,
                            ready_at,
                            window,
                            cast_time,
                            score / cast_time,
                            score,
                            state["charged_counts"],
                            state["charged_maxes"],
                        )
                        if not exact_tail
                        else (score / cast_time, 0.0)
                    )
                    wait = max(0.0, ready_at - state_time)
                    priority = adjusted_dpa * cast_time / max(
                        0.05,
                        cast_time + wait,
                    )
                    options.append((priority, ready_at, cast_time, metric))
                options.sort(key=lambda row: row[0], reverse=True)
                for _priority, ready_at, cast_time, metric in options[:branch_width]:
                    skill = self._skill_burst_skill_key(metric.get("skill"))
                    cast_previous = self._skill_burst_immediate_predecessor(
                        state.get("previous", ""),
                        as_number(state.get("time")),
                        ready_at,
                    )
                    future_attrs = self._skill_burst_new_scheme_1_state_attrs(
                        state,
                        support_actions,
                        ready_at,
                    )
                    score, _ = self._skill_burst_new_scheme_1_metric_value(
                        metric,
                        future_attrs,
                        ready_at,
                        planning_boundary,
                        cast_previous,
                        support_actions,
                    )
                    transition = self._skill_burst_new_scheme_1_apply_damage(
                        metric,
                        ready_at,
                        cast_time,
                        future_attrs,
                        state["available"],
                        base_cooldowns,
                        support_actions,
                        state["support_available"],
                        state["support_expires"],
                        state["charged_counts"],
                        state["charged_maxes"],
                        state["charged_recharge_at"],
                        int(state.get("ammo", 0)),
                        int(state.get("fury", 0)),
                        int(state.get("guardian", 0)),
                    )
                    expanded.append({
                        **transition,
                        "time": ready_at + cast_time,
                        "score": as_number(state.get("score")) + score,
                        "previous": skill,
                        "sequence": (*state.get("sequence", ()), skill),
                        "exact_tail": exact_tail,
                    })
            if not expanded:
                break
            expanded.sort(
                key=lambda state: self._skill_burst_new_scheme_1_terminal_value(
                    state,
                    candidates,
                    support_actions,
                    horizon_end,
                    planning_boundary,
                ),
                reverse=True,
            )
            states = expanded[:beam_width]
            if self._skill_burst_new_scheme_1_terminal_value(
                states[0], candidates, support_actions, horizon_end, planning_boundary
            ) > self._skill_burst_new_scheme_1_terminal_value(
                best, candidates, support_actions, horizon_end, planning_boundary
            ):
                best = states[0]
        planned_value = self._skill_burst_new_scheme_1_terminal_value(
            best,
            candidates,
            support_actions,
            horizon_end,
            planning_boundary,
        )
        return planned_value / max(0.05, horizon_end - current), tuple(
            best.get("sequence", (root_skill,))
        )

    def _skill_burst_new_scheme_1_rank_ready(self, *args, **kwargs):
        from ..fury_planner import rank_fury_key_nodes
        baseline = self._skill_burst_new_scheme_1_rank_ready_base(*args, **kwargs)
        return rank_fury_key_nodes(self, baseline, *args, **kwargs)

    def _skill_burst_new_scheme_1_rank_ready_base(
        self,
        ready: list[tuple[float, float, float, float, dict[str, Any]]],
        candidates: list[dict[str, Any]],
        damage_available_at: dict[str, float],
        base_cooldowns: dict[str, float],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        active_attrs: dict[str, Any],
        current: float,
        window: float,
        previous_skill: str,
        charged_counts: dict[str, int],
        charged_maxes: dict[str, int],
        charged_recharge_at: dict[str, float | None],
        ammo: int,
        fury: int,
        guardian_phantoms: int,
    ) -> list[tuple[float, float, float, float, dict[str, Any]]]:
        if not self._skill_burst_new_scheme_1_enabled():
            return ready
        # A sole ready opener can still represent a required two-skill DPA
        # package.  Let pair planning evaluate it so the root is ranked by the
        # complete chain instead of silently falling back to standalone DPA.
        if len(ready) <= 1 and not (
            ready
            and (
                self._skill_burst_required_followups(
                    ready[0][4].get("skill", "")
                )
                or self._skill_burst_dpa_package_followups(
                    ready[0][4].get("skill", "")
                )
            )
        ):
            return ready
        queued = list(getattr(self, "_skill_burst_new_scheme_1_plan_queue", []))
        ready_by_skill = {
            self._skill_burst_skill_key(item[4].get("skill")): item
            for item in ready
        }
        if queued:
            queued_skill = self._skill_burst_skill_key(queued[0])
            queued_item = ready_by_skill.get(queued_skill)
            if queued_item is not None:
                self._skill_burst_new_scheme_1_plan_queue = queued[1:]
                metric = dict(queued_item[4])
                metric["new_scheme_1_sequence"] = tuple(queued)
                metric["new_scheme_1_rank"] = max(
                    1.0,
                    max((as_number(item[0]) for item in ready), default=0.0) * 1000.0,
                )
                return [
                    (
                        metric["new_scheme_1_rank"] if item is queued_item else as_number(item[0]),
                        item[1],
                        item[2],
                        item[3],
                        metric if item is queued_item else item[4],
                    )
                    for item in ready
                ]
            self._skill_burst_new_scheme_1_plan_queue = []
        roots = []
        for item in ready:
            metric = item[4]
            direct_rank = max(0.0, as_number(item[0]))
            roots.append((direct_rank, item))
        roots.sort(key=lambda row: row[0], reverse=True)
        best_direct = max((row[0] for row in roots), default=0.0)
        direct_best_skill = self._skill_burst_skill_key(roots[0][1][4].get("skill")) if roots else ""
        planning_boundary = self._skill_burst_new_scheme_1_planning_boundary(
            current,
            window,
        )
        time_to_boundary = max(0.0, planning_boundary - current)
        crosses_boundary = bool(
            planning_boundary < window - 1e-6
            and any(
                max(0.0, -as_number(item[2])) > time_to_boundary + 1e-6
                for item in ready
            )
        )
        exact_tail = (
            time_to_boundary <= SKILL_BURST_STOP_BOUNDARY_TAIL_SECONDS + 1e-6
            or crosses_boundary
        )
        planned_candidates: list[tuple[float, tuple[Any, ...]]] = []
        for direct_rank, item in roots:
            skill = self._skill_burst_skill_key(item[4].get("skill"))
            hard_chain = (
                self._skill_burst_required_followups(skill)
                | self._skill_burst_forced_combo_followups(skill)
                | self._skill_burst_dpa_package_followups(skill)
            )
            related = hard_chain | self._skill_burst_optional_combo_followups(skill)
            cooldown_targets = {
                target_skill
                for target_skill, _source in self._skill_burst_cooldown_rule_sources_for(
                    skill
                )
            }
            cooldown_links = self._skill_burst_new_scheme_1_cooldown_links(skill)
            related |= cooldown_links
            related_dpa = max(
                (
                    self._skill_burst_candidate_metric_dpa(metric)
                    for metric in candidates
                    if self._skill_burst_skill_key(metric.get("skill")) in related
                ),
                default=0.0,
            )
            if not related:
                continue
            # Opportunity scoring may intentionally reduce a root to zero
            # because its animation would delay a stronger skill becoming
            # ready.  A cheap optional/cooldown pair must not resurrect that
            # rejected root with its raw damage.  Only a genuinely required
            # combo, or a source that actively refunds another skill's
            # cooldown, may cross that boundary.  The reverse relation is not
            # causal: a cooldown target (for example Destroy Roar) must not be
            # revived merely because another skill can reduce its cooldown.
            if direct_rank <= 1e-9 and not (hard_chain or cooldown_targets):
                continue
            cheap_package_rank = max(direct_rank, (direct_rank + related_dpa) / 2)
            if cheap_package_rank >= best_direct * 0.88 - 1e-9:
                planned_candidates.append((cheap_package_rank, item))
        planned_candidates.sort(key=lambda row: row[0], reverse=True)
        root_width = self._skill_burst_new_scheme_1_profile(window)[4]
        eligible_roots = [
            row
            for row in roots
            if row[0] > 1e-9
        ]
        eligible_planned = [
            row
            for row in planned_candidates
            if row[0] > 1e-9
        ]
        second_direct = eligible_roots[1][0] if len(eligible_roots) > 1 else 0.0
        ambiguity_ratio = max(
            0.0,
            min(
                1.0,
                as_number(
                    getattr(
                        self,
                        "_skill_burst_new_scheme_1_ambiguity_ratio",
                        0.90,
                    ),
                    0.90,
                ),
            ),
        )
        ambiguous_decision = bool(
            ambiguity_ratio > 0
            and best_direct > 1e-9
            and second_direct >= best_direct * ambiguity_ratio - 1e-9
        )
        pair_rows = (
            list(eligible_planned[:root_width])
            if getattr(self, "_skill_burst_new_scheme_1_pair_planning", True)
            else []
        )
        rollout_rows: list[tuple[float, tuple[Any, ...]]] = []
        if ambiguous_decision:
            rollout_rows.extend(eligible_roots[:root_width])
        if exact_tail:
            rollout_rows.extend(eligible_roots[: min(6, len(eligible_roots))])
        rollout_ids = {id(item) for _rank, item in rollout_rows}
        pair_ids = {
            id(item)
            for _rank, item in pair_rows
            if id(item) not in rollout_ids
        }
        planning_stats = getattr(self, "_skill_burst_new_scheme_1_planning_stats", None)
        if isinstance(planning_stats, dict):
            planning_stats["decisions"] = int(planning_stats.get("decisions", 0)) + 1
            if ambiguous_decision:
                planning_stats["ambiguous_decisions"] = int(
                    planning_stats.get("ambiguous_decisions", 0)
                ) + 1
            planning_stats["rollout_roots"] = int(
                planning_stats.get("rollout_roots", 0)
            ) + len(rollout_ids)
            planning_stats["pair_roots"] = int(
                planning_stats.get("pair_roots", 0)
            ) + len(pair_ids)
        ranked = []
        for direct_rank, item in roots:
            metric = dict(item[4])
            if id(item) in rollout_ids:
                plan_rank, sequence = self._skill_burst_new_scheme_1_rollout(
                    item,
                    candidates,
                    damage_available_at,
                    base_cooldowns,
                    support_actions,
                    support_available_at,
                    support_expires_at,
                    active_attrs,
                    current,
                    window,
                    previous_skill,
                    charged_counts,
                    charged_maxes,
                    charged_recharge_at,
                    ammo,
                    fury,
                    guardian_phantoms,
                    exact_tail,
                )
            elif id(item) in pair_ids:
                plan_rank, sequence = self._skill_burst_new_scheme_1_pair_plan(
                    item,
                    candidates,
                    damage_available_at,
                    base_cooldowns,
                    support_actions,
                    support_available_at,
                    support_expires_at,
                    active_attrs,
                    current,
                    window,
                    previous_skill,
                    charged_counts,
                    charged_maxes,
                    charged_recharge_at,
                    ammo,
                    fury,
                    guardian_phantoms,
                )
            else:
                plan_rank, sequence = direct_rank, (
                    self._skill_burst_skill_key(metric.get("skill")),
                )
            metric_skill = self._skill_burst_skill_key(metric.get("skill"))
            required_override_ratio = max(
                1.0,
                as_number(
                    getattr(
                        self,
                        "_skill_burst_new_scheme_1_override_ratio",
                        1.08,
                    ),
                    1.08,
                ),
            )
            if (
                not exact_tail
                and
                metric_skill != direct_best_skill
                and plan_rank < best_direct * required_override_ratio
            ):
                plan_rank = direct_rank
                sequence = (metric_skill,)
            metric["new_scheme_1_sequence"] = sequence
            metric["new_scheme_1_rank"] = plan_rank
            ranked.append((plan_rank, item[1], item[2], item[3], metric))
        self._skill_burst_new_scheme_1_last_choice = {
            "time": current,
            "ranked": [
                (self._skill_burst_skill_key(item[4].get("skill")), item[0])
                for item in sorted(ranked, key=lambda row: row[0], reverse=True)[:5]
            ],
        }
        trace = getattr(self, "_skill_burst_new_scheme_1_trace", None)
        if isinstance(trace, list):
            direct_by_skill = {
                self._skill_burst_skill_key(item[4].get("skill")): direct_rank
                for direct_rank, item in roots
            }
            trace.append({
                "type": "damage",
                "time": round(current, 5),
                "previous": self._skill_burst_skill_key(previous_skill),
                "ranked": [
                    {
                        "skill": self._skill_burst_skill_key(item[4].get("skill")),
                        "direct": direct_by_skill.get(
                            self._skill_burst_skill_key(item[4].get("skill")),
                            0.0,
                        ),
                        "planned": item[0],
                        "sequence": list(item[4].get("new_scheme_1_sequence", ())),
                    }
                    for item in sorted(ranked, key=lambda row: row[0], reverse=True)[:5]
                ],
            })
        best_row = max(ranked, key=lambda row: row[0], default=None)
        if best_row is not None:
            best_sequence = tuple(best_row[4].get("new_scheme_1_sequence", ()))
            first_skill = self._skill_burst_skill_key(best_sequence[0]) if best_sequence else ""
            linked = (
                self._skill_burst_required_followups(first_skill)
                | self._skill_burst_forced_combo_followups(first_skill)
                | self._skill_burst_optional_combo_followups(first_skill)
                | self._skill_burst_dpa_package_followups(first_skill)
            )
            self._skill_burst_new_scheme_1_plan_queue = [
                skill for skill in best_sequence[1:2]
                if (
                    exact_tail
                    or self._skill_burst_skill_key(skill) in linked
                )
            ]
        return ranked

    def _skill_burst_new_scheme_1_pair_plan(
        self,
        root: tuple[float, float, float, float, dict[str, Any]],
        candidates: list[dict[str, Any]],
        damage_available_at: dict[str, float],
        base_cooldowns: dict[str, float],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        active_attrs: dict[str, Any],
        current: float,
        window: float,
        previous_skill: str,
        charged_counts: dict[str, int],
        charged_maxes: dict[str, int],
        charged_recharge_at: dict[str, float | None],
        ammo: int,
        fury: int,
        guardian_phantoms: int,
    ) -> tuple[float, tuple[str, ...]]:
        """Evaluate one complete next action after each root without a tree."""
        planning_boundary = self._skill_burst_new_scheme_1_planning_boundary(
            current,
            window,
        )
        horizon = min(
            planning_boundary,
            current + self._skill_burst_new_scheme_1_profile(window)[0],
        )
        root_metric = root[4]
        root_skill = self._skill_burst_skill_key(root_metric.get("skill"))
        root_score, root_cast = self._skill_burst_new_scheme_1_metric_value(
            root_metric,
            active_attrs,
            current,
            planning_boundary,
            previous_skill,
            support_actions,
        )
        if root_cast <= 0:
            return max(0.0, as_number(root[0])), (root_skill,)
        transition = self._skill_burst_new_scheme_1_apply_damage(
            root_metric,
            current,
            root_cast,
            active_attrs,
            damage_available_at,
            base_cooldowns,
            support_actions,
            support_available_at,
            support_expires_at,
            charged_counts,
            charged_maxes,
            charged_recharge_at,
            ammo,
            fury,
            guardian_phantoms,
        )
        state = {
            **transition,
            "time": current + root_cast,
            "previous": root_skill,
        }
        root_opportunity_rank = max(0.0, as_number(root[0]))
        root_value = max(root_score, root_opportunity_rank * root_cast)
        best_rank = max(root_opportunity_rank, root_score / root_cast)
        best_sequence = (root_skill,)
        required = self._skill_burst_required_followups(root_skill)
        dpa_package = self._skill_burst_dpa_package_followups(root_skill)
        options: list[tuple[float, str]] = []
        linked_followups = (
            self._skill_burst_required_followups(root_skill)
            | self._skill_burst_forced_combo_followups(root_skill)
            | self._skill_burst_optional_combo_followups(root_skill)
            | dpa_package
            | self._skill_burst_new_scheme_1_cooldown_links(root_skill)
        )
        second_candidates = sorted(
            candidates,
            key=self._skill_burst_candidate_metric_dpa,
            reverse=True,
        )
        if linked_followups:
            second_candidates = [
                metric
                for metric in second_candidates
                if self._skill_burst_skill_key(metric.get("skill")) in linked_followups
            ]
        else:
            second_candidates = []
        for metric in second_candidates:
            skill = self._skill_burst_skill_key(metric.get("skill"))
            if not skill or (required and skill not in required):
                continue
            if self._skill_burst_ammo_cost(skill) > int(state.get("ammo", 0)):
                continue
            ready_at = max(as_number(state.get("time")), as_number(state["available"].get(skill)))
            if skill in state["charged_counts"] and state["charged_counts"].get(skill, 0) > 0:
                ready_at = as_number(state.get("time"))
            if ready_at >= horizon - 1e-6:
                continue
            cast_previous = self._skill_burst_immediate_predecessor(
                root_skill,
                as_number(state.get("time")),
                ready_at,
            )
            if not self._skill_burst_predecessor_satisfied(cast_previous, skill):
                continue
            future_attrs = self._skill_burst_new_scheme_1_state_attrs(
                state,
                support_actions,
                ready_at,
            )
            if not self._skill_burst_state_requirement_satisfied(skill, future_attrs):
                continue
            score, cast_time = self._skill_burst_new_scheme_1_metric_value(
                metric,
                future_attrs,
                ready_at,
                planning_boundary,
                cast_previous,
                support_actions,
            )
            if cast_time <= 0:
                continue
            adjusted_dpa, _wait_until = self._skill_burst_new_scheme_1_opportunity_score(
                metric,
                candidates,
                state["available"],
                base_cooldowns,
                support_actions,
                state["support_available"],
                state["support_expires"],
                future_attrs,
                ready_at,
                planning_boundary,
                cast_time,
                score / cast_time,
                score,
                state["charged_counts"],
                state["charged_maxes"],
            )
            elapsed = ready_at + cast_time - current
            pair_rank = (
                root_value + adjusted_dpa * cast_time
            ) / max(0.05, elapsed)
            options.append((pair_rank, skill))
        if options:
            pair_rank, skill = max(options, key=lambda row: row[0])
            # A required follow-up and its opener are one atomic action for
            # ranking purposes.  Keeping the opener's standalone DPA as the
            # floor can make a weak/long follow-up invisible to the planner
            # even though runtime must consume it immediately afterwards.
            if required or pair_rank > best_rank + 1e-9:
                best_rank = pair_rank
                best_sequence = (root_skill, skill)
        return best_rank, best_sequence

    def _skill_burst_is_short_personal_burst_action(
        self,
        action: dict[str, Any],
    ) -> bool:
        """Return whether an active buff should be aligned to a damage bundle."""
        if getattr(
            self,
            "_skill_burst_disable_short_personal_burst_scheduler",
            False,
        ):
            return False
        explicit = action.get("short_personal_burst")
        if explicit is not None:
            return bool(explicit)
        action_type = norm(action.get("type")).lower()
        duration = max(0.0, as_number(action.get("duration")))
        cooldown = max(0.0, as_number(action.get("base_cooldown")))
        if (
            "个人buff" not in action_type
            or not action.get("periodic_buff")
            or not (0.0 < duration <= 10.0 + 1e-6)
            or cooldown <= duration + 1e-6
            or action.get("mandatory_uptime")
            or action.get("triggered_only")
            or action.get("state_only")
            or action.get("state_dependents")
            or action.get("pinned_cast_schedule")
        ):
            return False
        if max(0.0, as_number(action.get("active_multiplier"), 1.0)) > max(
            1.0,
            as_number(action.get("inactive_multiplier"), 1.0),
        ) + 1e-6:
            return True
        timing_keys = {"冷却缩减%", "动作速度%", "攻速%"}
        return any(
            norm(key) in timing_keys and as_number(value) > 0
            for key, value in action.get("attrs", {}).items()
        )

    def _skill_burst_has_short_personal_burst_actions(
        self,
        support_actions: list[dict[str, Any]],
    ) -> bool:
        return any(
            self._skill_burst_is_short_personal_burst_action(action)
            for action in support_actions
        )

    def _skill_burst_new_scheme_1_support_value_seconds(
        self,
        action: dict[str, Any],
        current: float,
        cast_end: float,
        window: float,
        fallback_horizon: float,
    ) -> float:
        """Return the factual effect lifetime available for local valuation."""

        duration = max(0.0, as_number(action.get("duration")))
        if duration <= 0:
            return min(
                max(0.0, fallback_horizon),
                max(0.0, window - current),
            )
        effect_start, effect_end, _refresh_tail = (
            team_effect_application_window_for_attrs(
                action.get("skill", ""),
                action.get("attrs", {}),
                current,
                cast_end,
                duration,
                starts_on_cast=self._skill_burst_action_starts_on_cast(action),
                triggered_only=bool(action.get("triggered_only")),
            )
        )
        return max(
            0.0,
            min(window, effect_end) - max(current, effect_start),
        )

    def _skill_burst_new_scheme_1_choose_support(
        self,
        ready_support: list[tuple[Any, ...]],
        candidates: list[dict[str, Any]],
        support_actions: list[dict[str, Any]],
        support_available_at: dict[int, float],
        support_expires_at: dict[int, float],
        active_attrs: dict[str, Any],
        damage_available_at: dict[str, float],
        current: float,
        window: float,
        previous_skill: str,
        best_damage_dpa: float,
    ) -> tuple[Any, ...] | None:
        """Choose a support action by predicted net damage, not fixed ordering."""
        if not ready_support:
            return None
        deferred_snapshot_actions = {
            id(item[5])
            for item in ready_support
            if len(item) > 5
            and self._skill_burst_snapshot_action_should_defer(
                item[5],
                ready_support,
                active_attrs,
            )
        }
        if deferred_snapshot_actions:
            eligible_support = [
                item
                for item in ready_support
                if len(item) <= 5 or id(item[5]) not in deferred_snapshot_actions
            ]
            if eligible_support:
                ready_support = eligible_support

        # Once a declared snapshot boost is already active, do not spend its
        # limited duration on an ordinary damaging support cast before taking
        # the snapshot.  A still-ready stat booster is handled above by the
        # generic dependency deferral, while genuinely mandatory actions keep
        # their precedence below.  This therefore joins Avatar -> Judgement
        # when both are ready, but never delays Avatar until Judgement's next
        # cooldown window.
        boosted_snapshot = [
            item
            for item in ready_support
            if len(item) > 5
            and self._skill_burst_snapshot_action_has_active_boost(
                item[5],
                active_attrs,
            )
        ]
        mandatory_boosted_snapshot = [
            item for item in boosted_snapshot if item[0] == 0
        ]
        if mandatory_boosted_snapshot:
            # The runtime has already declared this snapshot refresh due now.
            # Do not let the generic "setup before mandatory" optimization
            # insert a debuff/damaging support cast into the capture window.
            self._skill_burst_new_scheme_1_plan_queue = []
            return min(
                mandatory_boosted_snapshot,
                key=lambda item: (item[1], item[2], item[3], item[4]),
            )
        if boosted_snapshot and not any(item[0] == 0 for item in ready_support):
            self._skill_burst_new_scheme_1_plan_queue = []
            return min(
                boosted_snapshot,
                key=lambda item: (item[1], item[2], item[3], item[4]),
            )
        support_candidate_limit = max(
            0,
            int(
                as_number(
                    getattr(
                        self,
                        "_skill_burst_new_scheme_1_support_candidate_limit",
                        0,
                    )
                )
            ),
        )
        evaluation_candidates = candidates
        if support_candidate_limit and len(candidates) > support_candidate_limit:
            linked_skills: set[str] = set()
            for item in ready_support:
                if len(item) <= 5:
                    continue
                action = item[5]
                action_skill = self._skill_burst_skill_key(action.get("skill"))
                linked_skills.update(
                    self._skill_burst_skill_key(skill)
                    for skill in action.get("state_dependents", ())
                )
                linked_skills.update(self._skill_burst_required_followups(action_skill))
                linked_skills.update(self._skill_burst_forced_combo_followups(action_skill))
            ranked_cache = getattr(
                self,
                "_skill_burst_support_ranked_candidates_cache",
                None,
            )
            if not isinstance(ranked_cache, dict):
                ranked_cache = {}
                self._skill_burst_support_ranked_candidates_cache = ranked_cache
            ranked_entry = ranked_cache.get(id(candidates))
            if (
                isinstance(ranked_entry, tuple)
                and len(ranked_entry) == 2
                and ranked_entry[0] is candidates
            ):
                ranked_candidates = ranked_entry[1]
            else:
                ranked_candidates = sorted(
                    candidates,
                    key=lambda metric: max(
                        self._skill_burst_candidate_metric_dpa(metric),
                        max(0.0, as_number(metric.get("effective_score")))
                        / max(
                            0.05,
                            as_number(metric.get("base_cooldown")),
                            as_number(metric.get("cast_time")),
                        ),
                    ),
                    reverse=True,
                )
                if len(ranked_cache) >= 64:
                    ranked_cache.pop(next(iter(ranked_cache)))
                # Retain the list object with the result so a recycled id can
                # never reuse another axis' ordering.
                ranked_cache[id(candidates)] = (
                    candidates,
                    ranked_candidates,
                )
            selected_ids = {
                id(metric) for metric in ranked_candidates[:support_candidate_limit]
            }
            evaluation_candidates = [
                metric
                for metric in candidates
                if id(metric) in selected_ids
                or self._skill_burst_skill_key(metric.get("skill")) in linked_skills
            ]
        mandatory = [item for item in ready_support if item[0] == 0]
        if mandatory:
            # A preferred/mandatory opener can still benefit from a short setup
            # buff.  The legacy scheduler returned here immediately, so a buff
            # such as an elemental self-buff was delayed until after the whole
            # opener even when it improved every following cast.  Only allow a
            # non-timing periodic buff to step in: state setters, CDR and action
            # speed retain their explicit opening semantics.
            hard_state_opener = any(
                item[5].get("state_dependents")
                or (
                    current <= 1e-6
                    and item[5].get("state_only")
                )
                for item in mandatory
                if len(item) > 5
            )
            setup_options: list[tuple[float, tuple[Any, ...]]] = []
            mandatory_cast_time = sum(
                max(
                    0.0,
                    self._skill_burst_support_cast_time(
                        item[5],
                        current,
                        active_attrs,
                    ),
                )
                for item in mandatory
            )
            dynamic_pair_order = bool(
                self._skill_burst_uses_dynamic_support_order()
                and not getattr(
                    self,
                    "_skill_burst_disable_team_objective_pair_order",
                    False,
                )
            )
            for item in ready_support:
                if not getattr(
                    self,
                    "_skill_burst_new_scheme_1_opening_setup_enabled",
                    True,
                ):
                    break
                if hard_state_opener:
                    break
                if item[0] == 0 or len(item) <= 5:
                    continue
                action = item[5]
                if self._skill_burst_snapshot_rule(action):
                    # A snapshot action must not become the setup placed before
                    # the stat buff it is intended to capture.  The dependency
                    # comes from job mechanics data rather than a skill name.
                    continue
                attrs = action.get("attrs", {})
                if (
                    not attrs
                    or not (
                        action.get("periodic_buff")
                        or (
                            dynamic_pair_order
                            and action.get("team_objective_effect")
                        )
                    )
                ):
                    continue
                metric = action.get("metric")
                if (
                    isinstance(metric, dict)
                    and max(
                        0.0,
                        as_number(metric.get("effective_score")),
                        as_number(action.get("effective_score")),
                    )
                    > 1e-6
                    and not (
                        dynamic_pair_order
                        and
                        action.get("team_objective_effect")
                        and action.get("team_objective_attrs")
                    )
                ):
                    continue
                if action.get("state_only") or action.get("state_dependents"):
                    continue
                if any(
                    norm(key) in {"冷却缩减%", "动作速度%"}
                    and as_number(value) > 0
                    for key, value in attrs.items()
                ):
                    continue
                gain_ratio = self._skill_burst_support_gain_ratio(
                    action,
                    active_attrs,
                    current,
                )
                cast_time = self._skill_burst_support_cast_time(
                    action,
                    current,
                    active_attrs,
                )
                duration = max(0.0, as_number(action.get("duration")))
                remaining = max(0.0, window - current - cast_time)
                useful_duration = min(duration, remaining, 30.0)
                if (
                    gain_ratio <= 1e-6
                    or cast_time <= 1e-6
                    or useful_duration <= mandatory_cast_time + 1e-6
                ):
                    continue
                # All mandatory setup actions are still cast. Compare the two
                # possible coverage rectangles instead of forcing either side:
                # candidate -> mandatory gives candidate_gain * setup_time;
                # mandatory -> candidate gives the best mandatory gain during
                # the candidate cast. This admits an early team amplifier (the
                # other seven members keep attacking during setup) while still
                # preserving a stronger personal/team mandatory effect when it
                # should genuinely go first.
                if dynamic_pair_order:
                    candidate_coverage = gain_ratio * min(
                        useful_duration,
                        mandatory_cast_time,
                    )
                    mandatory_counter_coverage = max(
                        (
                            self._skill_burst_support_gain_ratio(
                                mandatory_item[5],
                                active_attrs,
                                current,
                            )
                            * min(
                                cast_time,
                                max(
                                    0.0,
                                    as_number(
                                        mandatory_item[5].get("duration")
                                    ),
                                )
                                or cast_time,
                            )
                            for mandatory_item in mandatory
                            if len(mandatory_item) > 5
                        ),
                        default=0.0,
                    )
                    setup_gain = max(0.0, best_damage_dpa) * max(
                        0.0,
                        candidate_coverage - mandatory_counter_coverage,
                    )
                else:
                    covered_after_setup = max(
                        0.0,
                        min(useful_duration, mandatory_cast_time + 6.0)
                        - cast_time,
                    )
                    setup_gain = (
                        max(0.0, best_damage_dpa)
                        * gain_ratio
                        * covered_after_setup
                    )
                if setup_gain > 1e-6:
                    setup_options.append((setup_gain / cast_time, item))
            if setup_options:
                self._skill_burst_new_scheme_1_plan_queue = []
                return max(setup_options, key=lambda row: row[0])[1]
            self._skill_burst_new_scheme_1_plan_queue = []
            return min(
                mandatory,
                key=lambda item: (item[1], item[2], item[3], item[4]),
            )

        # Short personal burst buffs must not be spent on the remaining setup
        # actions.  Finish longer panel/element buffs and debuffs first, while still
        # allowing a short action-speed buff to accelerate that setup.  Once
        # setup is complete, evaluate the short buff immediately before the
        # next damage package instead of letting a damaging support cast consume
        # most of its duration.
        short_personal = [
            item
            for item in ready_support
            if len(item) > 5
            and self._skill_burst_is_short_personal_burst_action(item[5])
        ]
        if short_personal:
            timing_keys = {"冷却缩减%", "动作速度%", "攻速%"}

            def is_timing_short(item: tuple[Any, ...]) -> bool:
                return any(
                    norm(key) in timing_keys and as_number(value) > 0
                    for key, value in item[5].get("attrs", {}).items()
                )

            long_setup = [
                item
                for item in ready_support
                if len(item) > 5
                and item not in short_personal
                and item[5].get("periodic_buff")
                and max(0.0, as_number(item[5].get("duration"))) > 10.0 + 1e-6
                and not item[5].get("triggered_only")
                and self._skill_burst_support_gain_ratio(
                    item[5],
                    active_attrs,
                    current,
                ) > 1e-6
            ]
            if long_setup:
                ready_support = [
                    *[item for item in short_personal if is_timing_short(item)],
                    *long_setup,
                ]
            else:
                ready_support = short_personal

        horizon = min(
            max(
                2.0,
                as_number(
                    getattr(
                        self,
                        "_skill_burst_new_scheme_1_support_horizon",
                        12.0,
                    ),
                    12.0,
                ),
            ),
            max(0.0, window - current),
        )
        # Every ready support candidate compares itself with the same damage
        # pool at the same scheduler state.  The former inner loop recalculated
        # the complete metric score/cast/cooldown tuple once per support
        # action, even though none of those inputs contains that action.  Keep
        # one exact decision-local evaluation and reuse it below.  No rounded
        # key or cross-state cache is involved, so ordering and score formulas
        # are unchanged.
        evaluated_damage_candidates: list[
            tuple[
                dict[str, Any],
                str,
                float,
                float,
                float,
                float,
                float,
            ]
        ] = []
        evaluation_end = min(window, current + horizon)
        for metric in evaluation_candidates:
            damage_skill = self._skill_burst_skill_key(metric.get("skill"))
            if not damage_skill:
                continue
            ready_at = max(
                current,
                as_number(damage_available_at.get(damage_skill)),
            )
            if ready_at >= evaluation_end - 1e-6:
                continue
            score, damage_cast = self._skill_burst_new_scheme_1_metric_value(
                metric,
                active_attrs,
                ready_at,
                window,
                previous_skill,
                support_actions,
            )
            if score <= 0 or damage_cast <= 0:
                continue
            damage_dpa = score / damage_cast
            cooldown = 0.0
            if ready_at <= current + 1e-6:
                base_cooldown = self._skill_burst_original_cooldown(
                    damage_skill,
                    fallback=max(
                        0.0,
                        as_number(metric.get("base_cooldown")),
                    ),
                )
                cooldown = self._skill_burst_effective_cooldown(
                    damage_skill,
                    base_cooldown,
                    current,
                    active_attrs,
                )
            evaluated_damage_candidates.append((
                metric,
                damage_skill,
                ready_at,
                score,
                damage_cast,
                damage_dpa,
                cooldown,
            ))
        scored: list[tuple[float, tuple[Any, ...]]] = []
        cycle_bonus_by_index: dict[int, float] = {}
        # Cast time and support gain are pure for the current scheduler state.
        # The ordering pass below used to recompute both for every pair of
        # ready actions (O(n^2)), despite using the same ``current`` and
        # ``active_attrs`` each time.  Cache only inside this decision so no
        # value can leak across a cooldown/effect state transition.
        decision_cast_time: dict[int, float] = {}
        decision_gain_ratio: dict[int, float] = {}
        for ready_item in ready_support:
            if len(ready_item) <= 5:
                continue
            ready_action = ready_item[5]
            action_identity = id(ready_action)
            decision_cast_time[action_identity] = (
                self._skill_burst_support_cast_time(
                    ready_action,
                    current,
                    active_attrs,
                )
            )
            decision_gain_ratio[action_identity] = (
                self._skill_burst_support_gain_ratio(
                    ready_action,
                    active_attrs,
                    current,
                )
            )
        ready_cast_times = [
            (
                int(item[4]),
                decision_cast_time[id(item[5])],
            )
            for item in ready_support
            if len(item) > 5
        ]
        for item in ready_support:
            mandatory = item[0] == 0
            support_index = int(item[4])
            action = item[5]
            skill = self._skill_burst_skill_key(action.get("skill"))
            cast_time = decision_cast_time[id(action)]
            if cast_time <= 0:
                continue
            apply_at = current + cast_time
            duration = max(0.0, as_number(action.get("duration")))
            action_attrs = action.get("attrs", {})
            action_horizon = horizon
            if any(
                norm(key).startswith("__") and as_number(value) > 0
                for key, value in action_attrs.items()
            ):
                # Mode/state setters unlock a different action pool. Their
                # value materializes over more than the next few casts, so use
                # a slightly wider view than an ordinary stat buff/debuff.
                action_horizon = min(
                    max(
                        horizon,
                        as_number(
                            getattr(
                                self,
                                "_skill_burst_new_scheme_1_state_support_horizon",
                                12.0,
                            ),
                            12.0,
                        ),
                    ),
                    max(0.0, window - current),
                )
            # Value a support action over its factual effect lifetime.  The
            # old receding-horizon estimate capped every ordinary support
            # effect at 12 seconds, which systematically undervalued long
            # buffs/debuffs such as Aim and Heavy Duck. Delayed application,
            # refresh tails and the current Boss boundary use the same timing
            # rules as runtime state. Duration-less setup actions retain the
            # historical bounded fallback.
            sample_horizon = (
                self._skill_burst_new_scheme_1_support_value_seconds(
                    action,
                    current,
                    apply_at,
                    window,
                    action_horizon,
                )
            )
            own_metric = action.get("metric")
            own_score = (
                self._skill_burst_window_metric_score(
                    own_metric,
                    self._skill_burst_attrs_during_action(active_attrs, action),
                    current,
                    window,
                    cast_time,
                )
                if isinstance(own_metric, dict)
                else max(0.0, as_number(action.get("effective_score")))
            )
            competing_cast = min(
                (
                    value
                    for other_index, value in ready_cast_times
                    if other_index != support_index and value > 1e-6
                ),
                default=0.0,
            )
            cycle_preservation_bonus = 0.0
            support_cooldown = self._skill_burst_support_cooldown(
                action,
                current,
                active_attrs,
            )
            if own_score > 0 and support_cooldown > 1e-6 and competing_cast > 0:
                def visible_cast_units(delay: float) -> float:
                    units = 0.0
                    start_at = current + max(0.0, delay)
                    guard = 0
                    while start_at < window - 1e-6 and guard < 64:
                        units += min(
                            1.0,
                            max(0.0, window - start_at) / max(0.05, cast_time),
                        )
                        start_at += support_cooldown
                        guard += 1
                    return units

                cycle_preservation_bonus = own_score * max(
                    0.0,
                    visible_cast_units(0.0) - visible_cast_units(competing_cast),
                )
            cycle_bonus_by_index[support_index] = cycle_preservation_bonus
            damage_reference_dpa = max(0.0, best_damage_dpa)
            future_displaced_score = 0.0
            cast_urgency_loss = 0.0
            remaining_window_scale = min(
                1.0,
                (30.0 / max(30.0, window - current)) ** 2,
            )
            for (
                metric,
                damage_skill,
                ready_at,
                score,
                damage_cast,
                damage_dpa,
                cooldown,
            ) in evaluated_damage_candidates:
                if damage_skill == skill:
                    continue
                wait = max(0.0, ready_at - current)
                damage_reference_dpa = max(
                    damage_reference_dpa,
                    score / max(0.05, damage_cast + min(wait, 2.0)),
                )
                if current + 1e-6 < ready_at < apply_at - 1e-6:
                    future_displaced_score = max(
                        future_displaced_score,
                        damage_dpa * (apply_at - ready_at),
                    )
                if ready_at > current + 1e-6:
                    continue
                if cooldown <= 1e-6:
                    continue
                remaining_window = max(0.0, window - current - damage_cast)
                future_uses = max(0, int(remaining_window // cooldown))
                latest_start = window - damage_cast - future_uses * cooldown
                slack = max(0.0, latest_start - current)
                if cast_time > slack + 1e-6:
                    cast_urgency_loss = max(
                        cast_urgency_loss,
                        score * remaining_window_scale,
                    )
                elif slack < max(2.0, cast_time * 2):
                    cast_urgency_loss = max(
                        cast_urgency_loss,
                        score
                        * remaining_window_scale
                        * 0.35
                        * cast_time
                        / max(0.05, slack + cast_time),
                    )
            for other_index, other_action in enumerate(support_actions):
                if other_index == support_index:
                    continue
                ready_at = as_number(support_available_at.get(other_index))
                if not (current + 1e-6 < ready_at < apply_at - 1e-6):
                    continue
                other_metric = other_action.get("metric")
                if not isinstance(other_metric, dict):
                    continue
                other_cast = self._skill_burst_support_cast_time(
                    other_action,
                    ready_at,
                    active_attrs,
                )
                if other_cast <= 0:
                    continue
                other_attrs = self._skill_burst_attrs_for_cast(
                    self._skill_burst_attrs_during_action(active_attrs, other_action),
                    other_action.get("skill"),
                )
                other_score = self._skill_burst_window_metric_score(
                    other_metric,
                    other_attrs,
                    ready_at,
                    window,
                    other_cast,
                )
                if other_score <= 0:
                    continue
                future_displaced_score = max(
                    future_displaced_score,
                    other_score / other_cast * (apply_at - ready_at),
                )
            dependent_keys = {
                self._skill_burst_skill_key(value)
                for value in action.get("state_dependents", ())
            }
            gain_ratio = decision_gain_ratio[id(action)]
            timing_attrs = action.get("attrs", {})
            gain_ratio += min(
                0.70,
                max(0.0, as_number(timing_attrs.get("冷却缩减%"))) / 100,
            ) * 0.55
            gain_ratio += min(
                1.00,
                max(0.0, as_number(timing_attrs.get("动作速度%"))) / 100,
            ) * 0.90
            gain = damage_reference_dpa * sample_horizon * gain_ratio
            if dependent_keys:
                dependent_dpa = max(
                    (
                        self._skill_burst_candidate_metric_dpa(metric)
                        for metric in evaluation_candidates
                        if self._skill_burst_skill_key(metric.get("skill"))
                        in dependent_keys
                    ),
                    default=0.0,
                )
                gain += max(
                    dependent_dpa * min(sample_horizon, 4.0) * 0.85,
                    damage_reference_dpa * cast_time,
                )
            benefit_rate = (
                own_score
                + gain
                + cycle_preservation_bonus
                - future_displaced_score
                - cast_urgency_loss
            ) / cast_time
            # Keep support valuation single-sourced.  The shared opportunity
            # model includes semantic benefits that plain attrs cannot express
            # (for example Holy Ground doubling its linked attacks).  Reusing
            # it here prevents the pure scheduler from discarding those gains
            # and choosing an ordinary damage cast first.
            hard_followups = (
                self._skill_burst_required_followups(skill)
                | self._skill_burst_forced_combo_followups(skill)
            )
            semantic_followups = dependent_keys | hard_followups
            if semantic_followups:
                benefit_rate = max(
                    benefit_rate,
                    self._skill_burst_support_opportunity_dpa(
                        action,
                        current,
                        active_attrs,
                        evaluation_candidates,
                        window,
                    ),
                )
            if hard_followups:
                linked_dpa = max(
                    (
                        self._skill_burst_candidate_metric_dpa(metric)
                        for metric in evaluation_candidates
                        if self._skill_burst_skill_key(metric.get("skill"))
                        in hard_followups
                    ),
                    default=0.0,
                )
                benefit_rate = max(
                    benefit_rate,
                    linked_dpa,
                )
            opportunity_rate = max(0.0, best_damage_dpa)
            net_rank = benefit_rate - opportunity_rate * 0.92
            if mandatory:
                net_rank += max(1.0, opportunity_rate) * 1000.0
            scored.append((net_rank, item))
        if not scored:
            return None
        # When two useful support actions are ready together, their standalone
        # ranks cannot decide the best order.  Prefer the action that improves
        # the damage or cast time of the other action.  This keeps the rule
        # generic for attack buffs followed by damaging debuffs and similar
        # openers instead of hard-coding job-specific sequences.
        ordered_scores: list[tuple[float, tuple[Any, ...]]] = []
        order_bonus_by_index: dict[int, float] = {}
        for net_rank, item in scored:
            action = item[5]
            cast_time = decision_cast_time[id(action)]
            ordered_rank = net_rank
            action_gain_ratio = decision_gain_ratio[id(action)]
            action_attrs = action.get("attrs", {})
            timing_support = any(
                norm(key) in {"冷却缩减%", "动作速度%"}
                and as_number(value) > 0
                for key, value in action_attrs.items()
            )
            if (
                cast_time > 0
                and action_gain_ratio > 1e-9
                and action_attrs
                and not timing_support
            ):
                visible_attrs = {
                    key: value
                    for key, value in active_attrs.items()
                    if not norm(key).startswith("__")
                }
                effects = [
                    {
                        "row": -1,
                        "skill": "active",
                        "attrs": visible_attrs,
                        "effective_attrs": visible_attrs,
                    },
                    {
                        "row": action.get("order", 0),
                        "skill": action.get("skill", ""),
                        "attrs": action.get("attrs", {}),
                        "effective_attrs": action.get("attrs", {}),
                    },
                ]
                attrs_after = self._skill_burst_cached_merged_team_attrs(
                    effects
                )
                for key, value in active_attrs.items():
                    if norm(key).startswith("__"):
                        attrs_after[norm(key)] = value
                other_start = current + cast_time
                for other_rank, other_item in scored:
                    if other_item is item or other_rank <= 0:
                        continue
                    other_action = other_item[5]
                    other_cast = decision_cast_time[id(other_action)]
                    other_gain_ratio = decision_gain_ratio[id(other_action)]
                    # Both setup actions will be cast. Their only ordering
                    # difference is which effect is already active while the
                    # provider performs the second action. Compare those two
                    # coverage rectangles directly. The gain ratio already
                    # includes the owner and the weighted teammates, so this
                    # also values background team damage during setup without
                    # naming a profession or skill. A before B is preferable
                    # when gain(A) * cast(B) exceeds gain(B) * cast(A).
                    if (
                        self._skill_burst_uses_dynamic_support_order()
                        and not getattr(
                            self,
                            "_skill_burst_disable_team_objective_pair_order",
                            False,
                        )
                    ):
                        pair_coverage_gain = max(0.0, best_damage_dpa) * (
                            action_gain_ratio * other_cast
                            - other_gain_ratio * cast_time
                        )
                        if pair_coverage_gain > 1e-6:
                            ordered_rank = max(
                                ordered_rank,
                                other_rank
                                + pair_coverage_gain
                                / max(0.05, cast_time + other_cast),
                            )
                    other_metric = other_action.get("metric")
                    if not isinstance(other_metric, dict):
                        continue
                    base_cast = other_cast
                    improved_cast = self._skill_burst_support_cast_time(
                        other_action,
                        other_start,
                        attrs_after,
                    )
                    if base_cast <= 0 or improved_cast <= 0:
                        continue
                    base_score = self._skill_burst_window_metric_score(
                        other_metric,
                        self._skill_burst_attrs_during_action(
                            active_attrs,
                            other_action,
                        ),
                        other_start,
                        window,
                        base_cast,
                    )
                    improved_score = self._skill_burst_window_metric_score(
                        other_metric,
                        self._skill_burst_attrs_during_action(
                            attrs_after,
                            other_action,
                        ),
                        other_start,
                        window,
                        improved_cast,
                    )
                    order_gain = max(0.0, improved_score - base_score)
                    if order_gain <= 1e-6:
                        continue
                    ordered_rank = max(
                        ordered_rank,
                        other_rank
                        + order_gain / max(0.05, cast_time + improved_cast),
                    )
            order_bonus_by_index[int(item[4])] = max(0.0, ordered_rank - net_rank)
            ordered_scores.append((ordered_rank, item))
        scored = ordered_scores
        scored.sort(key=lambda row: row[0], reverse=True)
        best_rank, best_item = scored[0]
        if best_rank > 0:
            near_best = [
                row for row in scored
                if row[0] >= best_rank * 0.992 - 1e-9
            ]
            if len(near_best) > 1:
                best_rank, best_item = max(
                    near_best,
                    key=lambda row: (
                        int(
                            self._skill_burst_action_starts_on_cast(
                                row[1][5]
                            )
                        ),
                        order_bonus_by_index.get(int(row[1][4]), 0.0),
                        cycle_bonus_by_index.get(int(row[1][4]), 0.0),
                        row[0],
                    ),
                )
        trace = getattr(self, "_skill_burst_new_scheme_1_trace", None)
        if isinstance(trace, list):
            trace.append({
                "type": "support",
                "time": round(current, 5),
                "ranked": [
                    {
                        "skill": self._skill_burst_skill_key(item[1][5].get("skill")),
                        "rank": item[0],
                        "attrs": item[1][5].get("attrs", {}),
                        "periodic_buff": bool(item[1][5].get("periodic_buff")),
                    }
                    for item in scored[:5]
                ],
                "selected": (
                    self._skill_burst_skill_key(best_item[5].get("skill"))
                    if best_rank > 0
                    else ""
                ),
            })
        if best_rank > 0:
            self._skill_burst_new_scheme_1_plan_queue = []
            return best_item
        return None
