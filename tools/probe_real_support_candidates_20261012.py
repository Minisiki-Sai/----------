"""Measure real-data candidate evaluation, not a production schedule optimizer.

Direct effects: five whole-schedule offsets, exact final support evaluator.
Timing effects: two whole-schedule offsets, all recipient axes rerun.
Offsets are requests; this does not certify every direct candidate's legality.
No uploads. Baseline input is generated by bench_real_support_schedule_20261012.
"""
import argparse
import copy
import json
import pickle
import sys
import time
from dataclasses import replace
from collections import defaultdict
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))

def main():
    p=argparse.ArgumentParser()
    p.add_argument('bundle',type=Path)
    p.add_argument('--timing',action='store_true')
    p.add_argument('--offsets',type=float,nargs='+',default=None,
                   help='Diagnostic whole-schedule shifts only; not a legal peak scheduler.')
    p.add_argument('--output',type=Path,default=None)
    a=p.parse_args()
    from dragon_nest_builder.calculator import BuildCalculator
    from dragon_nest_builder.data_loader import DataStore
    from dragon_nest_builder.live_dps.scoring import TeamScoreEngine
    from dragon_nest_builder.v410_legacy_timeline import LegacyTimelineService
    from dragon_nest_builder import timeline_parallel
    data=pickle.loads(a.bundle.read_bytes())
    store=DataStore.load()
    engine=TeamScoreEngine(store)
    for key,value in data['engine_config'].items(): setattr(engine,key,value)
    context=data['context']
    end=max(e.timestamp_ms for e in context.team_damage_events)/1000
    timing_names={'精神爆发','时间加速','鸡尾酒','灼热火焰'}
    grouped=defaultdict(list)
    for effect in context.effects:
        e=effect.expectation
        if e.kind.casefold()=='debuff' or e.skill_key in timing_names: continue
        if not (0<e.duration<e.cooldown) or not effect.intervals: continue
        grouped[(effect.source_id,e.skill_key)].append(effect)
    report=dict(capture=data['capture'],baseline_score_seconds=data['score_seconds'],damage_events=len(context.team_damage_events),experimental=True,production_changes=False,scope='cost of bounded candidates; not a complete legal optimized rescore',direct=[])
    if not a.timing:
        st=time.perf_counter()
        for (source,skill),effects in grouped.items():
            taskstart=time.perf_counter()
            values=[]
            replacement_rows=[]
            for offset in (a.offsets if a.offsets is not None else (-5,-2,0,2,5)):
                # Keep the provider's other effects on their observed schedules.
                replacements={
                    (e.expectation.skill_key,e.expectation.effect_key,e.expectation.kind):tuple((max(0,x+offset),min(end,y+offset)) for x,y in e.intervals if y+offset>0 and x+offset<end)
                    for e in effects}
                replacement_rows.append(replacements)
                contributions,details=engine._counterfactual_support_contributions(context,replacement_source_id=source,replacement_intervals=replacements)
                gain=sum(details.get(engine._support_effect_identity(source,e.expectation),0) for e in effects)
                values.append(dict(offset=offset,contribution=gain))
            full_seconds=time.perf_counter()-taskstart
            faststart=time.perf_counter()
            intervals=sorted((x,y) for r in replacement_rows for rows in r.values() for x,y in rows)
            merged=[]
            for x,y in intervals:
                if merged and x<=merged[-1][1]: merged[-1][1]=max(merged[-1][1],y)
                else: merged.append([x,y])
            indexes=[]
            cursor=0
            for i,event in enumerate(context.team_damage_events):
                seconds=event.timestamp_ms/1000
                while cursor<len(merged) and seconds>merged[cursor][1]+1e-6: cursor+=1
                if cursor<len(merged) and seconds>=merged[cursor][0]-1e-6: indexes.append(i)
            local=replace(context,team_damage_events=tuple(context.team_damage_events[i] for i in indexes),baseline_damage_by_event=tuple(context.baseline_damage_by_event[i] for i in indexes))
            fast_values=[]
            for replacements in replacement_rows:
                _,details=engine._counterfactual_support_contributions(local,replacement_source_id=source,replacement_intervals=replacements)
                fast_values.append(sum(details.get(engine._support_effect_identity(source,e.expectation),0) for e in effects))
            fast_seconds=time.perf_counter()-faststart
            error=max(abs(r['contribution']-fast) for r,fast in zip(values,fast_values))
            assert error<1e-8,(source,skill,error)
            row=dict(source=source,skill=skill,effects=[e.expectation.effect_key for e in effects],seconds=full_seconds,filtered_seconds=fast_seconds,filtered_event_count=len(indexes),max_error_percent_points=error,candidates=values)
            report['direct'].append(row)
            print(json.dumps(row,ensure_ascii=False),flush=True)
        report['direct_total_seconds']=time.perf_counter()-st
        report['full_sweep_search_seconds']=sum(r['seconds'] for r in report['direct'])
        report['filtered_search_seconds']=sum(r['filtered_seconds'] for r in report['direct'])
    else:
        runtime=LegacyTimelineService(store,BuildCalculator(store)).extreme_runtime(copy.deepcopy(store.defaults['build1']))
        base_specs=data['specs']
        units=set()
        empty_units=set()
        for spec in base_specs.values():
            for (provider,skill),casts in spec.get('cast_schedule',{}).items():
                if skill in timing_names:
                    (units if casts else empty_units).add((provider,skill))
        report['empty_timing_units_excluded']=list(sorted(empty_units-units))
        tasks=[]
        labels=[]
        for provider,skill in sorted(units):
            for offset in (-2,2):
                for source,base in base_specs.items():
                    spec=copy.deepcopy(base)
                    spec.pop('score_exclusion_context',None)
                    spec['score_actual_casts_by_source']={}
                    spec['include_display_windows']=False
                    spec['timing_ablation_glyphs']=copy.deepcopy(data['plans'].get(source,{}).get('_score_glyphs',[]))
                    spec['_timing_ablation_source']=source
                    casts=spec.get('cast_schedule',{})
                    if (provider,skill) in casts:
                        casts[(provider,skill)]=[(max(0,x+offset),max(.001,y+offset)) for x,y in casts[(provider,skill)] if y+offset>0 and x+offset<spec['window']]
                    tasks.append(spec)
                    labels.append((provider,skill,offset,source))
        print(f'TIMING_START {len(units)} units {len(tasks)} axes',flush=True)
        st=time.perf_counter()
        try:
            results=runtime._extreme_timeline_tasks_parallel(tasks,progress_callback=lambda done,index,job:print(f'{time.perf_counter()-st:.2f}s {done}/{len(tasks)} {job}',flush=True))
            report['timing_total_seconds']=time.perf_counter()-st
            totals=defaultdict(float)
            for label,result in zip(labels,results): totals[label[:3]]+=float(result['dps'])
            report['timing']=[dict(provider=k[0],skill=k[1],offset=k[2],team_dps=v) for k,v in totals.items()]
            report['timing_axis_count']=len(tasks)
            report['timing_units']=list(sorted(units))
            report['timing_pool_status']=timeline_parallel.timeline_process_pool_status()
        finally: timeline_parallel.reset_timeline_process_pool()
    report['direct_offsets_seconds']=a.offsets if a.offsets is not None else [-5,-2,0,2,5]
    path=a.output or a.bundle.with_name(a.bundle.stem+('_timing_candidates' if a.timing else '_direct_candidates')+'.json')
    path.write_text(json.dumps(report,ensure_ascii=False,indent=2,default=str),encoding='utf8')
    print(path,flush=True)
if __name__=='__main__': main()
